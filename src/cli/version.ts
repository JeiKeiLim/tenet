import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

let cached: string | undefined;

export function getPackageVersion(): string {
  if (cached) return cached;
  const currentFile = fileURLToPath(import.meta.url);
  const pkgPath = path.resolve(path.dirname(currentFile), '../../package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8')) as { version: string };
  cached = pkg.version;
  return cached;
}

/**
 * Version stamp injected by `tenet init` into every installed SKILL.md copy
 * (see injectGeneratedSkillMetadata in src/cli/init.ts). This comment is the
 * only record of which Tenet version last refreshed the project's skills.
 */
const SKILL_STAMP_PATTERN = /<!-- Generated by Tenet (\S+) from /;

/** Skill copy locations Tenet installs; both are refreshed by tenet init --upgrade. */
export const SKILL_COPY_PATHS = ['.claude/skills/tenet/SKILL.md', '.agents/skills/tenet/SKILL.md'] as const;

/**
 * Read the version stamp from an installed SKILL.md copy.
 * undefined = the file is not there; null = present but the stamp comment is
 * missing (hand-edited copy, or a pre-stamp Tenet install).
 */
export function readSkillStampVersion(skillPath: string): string | null | undefined {
  let content: string;
  try {
    content = fs.readFileSync(skillPath, 'utf8');
  } catch {
    return undefined;
  }
  const match = content.match(SKILL_STAMP_PATTERN);
  return match ? match[1] : null;
}

/** Component-wise CalVer comparison: negative when a is older, 0 when equal. */
export function compareCalVer(a: string, b: string): number {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i += 1) {
    const da = pa[i] ?? 0;
    const db = pb[i] ?? 0;
    if (da !== db) return da - db;
  }
  return 0;
}

const stampHint = (stamp: string, cliVersion: string): string => {
  const cmp = compareCalVer(stamp, cliVersion);
  if (cmp === 0) return ' — up to date';
  if (cmp < 0) return ' — stale, run `tenet init --upgrade`';
  return ' — newer than the global CLI';
};

/**
 * Build the `tenet --version` report. Outside a Tenet project this is exactly
 * today's bare version. Inside one (cwd only — never walked up from parents),
 * each installed skill copy's stamped version is reported against the CLI
 * version so npm-upgrade-without-`tenet init --upgrade` drift is visible.
 * Read-only and fail-open: any error degrades to the bare version.
 */
export function formatVersionReport(cwd: string = process.cwd()): string {
  const cliVersion = getPackageVersion();
  try {
    const copies: { location: string; version: string | null | undefined }[] = SKILL_COPY_PATHS.map(
      (location) => ({ location, version: readSkillStampVersion(path.join(cwd, location)) }),
    );

    const found = copies.filter((copy) => copy.version !== undefined);
    const inProject = found.length > 0 || fs.existsSync(path.join(cwd, '.tenet'));
    if (!inProject) {
      return `${cliVersion}\n`;
    }

    const lines = [`tenet ${cliVersion}`];
    if (found.length === 0) {
      lines.push('skills: no installed skill copies found (run `tenet init --upgrade` to reinstall)');
    } else {
      const byVersion = new Map<string, string[]>();
      for (const copy of found) {
        const version = copy.version ?? 'unknown';
        const locations = byVersion.get(version) ?? [];
        locations.push(copy.location.replace(/\/SKILL\.md$/, ''));
        byVersion.set(version, locations);
      }
      for (const [version, locations] of byVersion) {
        const hint =
          version === 'unknown'
            ? ' — version stamp missing, `tenet init --upgrade` refreshes it'
            : stampHint(version, cliVersion);
        lines.push(`skills: ${version} (${locations.join(', ')})${hint}`);
      }
    }
    return `${lines.join('\n')}\n`;
  } catch {
    return `${cliVersion}\n`;
  }
}
