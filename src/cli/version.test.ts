import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  compareCalVer,
  formatVersionReport,
  getPackageVersion,
  readSkillStampVersion,
} from './version.js';

const CLI_VERSION = getPackageVersion();

const tempDirs: string[] = [];

const makeTempDir = (): string => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tenet-version-test-'));
  tempDirs.push(dir);
  return dir;
};

afterEach(() => {
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop();
    if (dir) fs.rmSync(dir, { recursive: true, force: true });
  }
});

/** Write an installed SKILL.md copy shaped like tenet init's injectGeneratedSkillMetadata. */
const writeSkillCopy = (
  projectPath: string,
  location: '.claude/skills/tenet' | '.agents/skills/tenet',
  stampVersion: string | 'none',
): void => {
  const skillPath = path.join(projectPath, location, 'SKILL.md');
  fs.mkdirSync(path.dirname(skillPath), { recursive: true });
  const stamp =
    stampVersion === 'none'
      ? ''
      : `<!-- Generated by Tenet ${stampVersion} from skills/tenet/SKILL.md. Run \`tenet init --upgrade\` after upgrading Tenet to refresh this copy. -->\n`;
  fs.writeFileSync(
    skillPath,
    `---\nname: tenet\n---\n\n${stamp}\nLong-running autonomous development orchestration.\n`,
    'utf8',
  );
};

describe('readSkillStampVersion', () => {
  it('parses the version from the generated stamp comment', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', '26.10.2');
    expect(readSkillStampVersion(path.join(dir, '.claude/skills/tenet/SKILL.md'))).toBe('26.10.2');
  });

  it('returns undefined when the copy is missing', () => {
    const dir = makeTempDir();
    expect(readSkillStampVersion(path.join(dir, '.claude/skills/tenet/SKILL.md'))).toBeUndefined();
  });

  it('returns null when the copy exists but has no stamp comment', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', 'none');
    expect(readSkillStampVersion(path.join(dir, '.claude/skills/tenet/SKILL.md'))).toBeNull();
  });
});

describe('compareCalVer', () => {
  it('orders CalVer component-wise', () => {
    expect(compareCalVer('26.11.0', '26.11.0')).toBe(0);
    expect(compareCalVer('26.10.2', '26.11.0')).toBeLessThan(0);
    expect(compareCalVer('26.11.1', '26.11.0')).toBeGreaterThan(0);
    expect(compareCalVer('27.1.0', '26.11.0')).toBeGreaterThan(0);
    // Missing components count as zero (defensive; stamps are always YY.MM.PATCH).
    expect(compareCalVer('26.11', '26.11.0')).toBe(0);
  });
});

describe('formatVersionReport', () => {
  it('prints only the bare CLI version outside a Tenet project', () => {
    const dir = makeTempDir();
    expect(formatVersionReport(dir)).toBe(`${CLI_VERSION}\n`);
  });

  it('reports matching copies as up to date', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', CLI_VERSION);
    writeSkillCopy(dir, '.agents/skills/tenet', CLI_VERSION);
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        `skills: ${CLI_VERSION} (.claude/skills/tenet, .agents/skills/tenet) — up to date\n`,
    );
  });

  it('flags older copies as stale with the upgrade command', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', '26.10.2');
    writeSkillCopy(dir, '.agents/skills/tenet', '26.10.2');
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        'skills: 26.10.2 (.claude/skills/tenet, .agents/skills/tenet) — stale, run `tenet init --upgrade`\n',
    );
  });

  it('flags copies stamped by a newer tenet than the global CLI', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', '99.1.0');
    writeSkillCopy(dir, '.agents/skills/tenet', '99.1.0');
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        'skills: 99.1.0 (.claude/skills/tenet, .agents/skills/tenet) — newer than the global CLI\n',
    );
  });

  it('prints one skills line per location when the copies disagree', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', CLI_VERSION);
    writeSkillCopy(dir, '.agents/skills/tenet', '26.10.2');
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        `skills: ${CLI_VERSION} (.claude/skills/tenet) — up to date\n` +
        'skills: 26.10.2 (.agents/skills/tenet) — stale, run `tenet init --upgrade`\n',
    );
  });

  it('reports a lone copy with a single location', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', CLI_VERSION);
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        `skills: ${CLI_VERSION} (.claude/skills/tenet) — up to date\n`,
    );
  });

  it('hints at reinstalling when .tenet exists but no skill copies do', () => {
    const dir = makeTempDir();
    fs.mkdirSync(path.join(dir, '.tenet'));
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        'skills: no installed skill copies found (run `tenet init --upgrade` to reinstall)\n',
    );
  });

  it('reports unknown when a copy exists without the stamp comment', () => {
    const dir = makeTempDir();
    writeSkillCopy(dir, '.claude/skills/tenet', 'none');
    expect(formatVersionReport(dir)).toBe(
      `tenet ${CLI_VERSION}\n` +
        'skills: unknown (.claude/skills/tenet) — version stamp missing, `tenet init --upgrade` refreshes it\n',
    );
  });
});
